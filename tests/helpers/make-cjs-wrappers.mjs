// Regenerates helpers/firestore-cjs.mjs and helpers/rules-unit-testing-cjs.mjs (run from the tests folder after changing the firebase version):
//   node helpers/make-cjs-wrappers.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const names = Object.keys(require('firebase/firestore')).filter((k) => /^[A-Za-z_$][\w$]*$/.test(k) && k !== 'default');
writeFileSync(new URL('./firestore-cjs.mjs', import.meta.url),
`// GENERATED by helpers/make-cjs-wrappers.mjs. Loads the CommonJS build of firebase/firestore so the app code, the test file and
// @firebase/rules-unit-testing all use ONE copy of the SDK (mixing the ESM and CommonJS builds makes doc() reject the Firestore object).
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const sdk = require('firebase/firestore');
export default sdk;
export const {
  ${names.join(',\n  ')}
} = sdk;
`);
writeFileSync(new URL('./rules-unit-testing-cjs.mjs', import.meta.url),
`// GENERATED by helpers/make-cjs-wrappers.mjs. CommonJS build of @firebase/rules-unit-testing (same SDK copy as firestore-cjs.mjs).
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const rut = require('@firebase/rules-unit-testing');
export default rut;
export const { initializeTestEnvironment, assertSucceeds, assertFails, withFunctionTriggersDisabled } = rut;
`);
console.log('wrote', names.length, 'firestore exports');
